#!/usr/bin/env bash
# Ubuntu 24.04+ restricts unprivileged user namespaces with AppArmor
# (kernel.apparmor_restrict_unprivileged_userns=1), so Electron's sandbox
# cannot start from node_modules and aborts with "The SUID sandbox helper
# binary was found, but is not configured correctly".
#
# This installs an AppArmor profile that allows user namespaces for this
# project's Electron binary only. Run it once; it survives `npm install`
# as long as the project stays in the same folder.
set -euo pipefail

DIR="$(cd "$(dirname "$0")/.." && pwd)"
ELECTRON="$DIR/node_modules/electron/dist/electron"
NAME="electron-shiodoki-dev"
PROFILE="/etc/apparmor.d/$NAME"

if [ ! -x "$ELECTRON" ]; then
  echo "Electron is not installed yet. Run 'npm install' first." >&2
  exit 1
fi
if ! command -v apparmor_parser >/dev/null 2>&1; then
  echo "AppArmor is not available on this system; nothing to do."
  exit 0
fi

echo "Installing $PROFILE for:"
echo "  $ELECTRON"
sudo tee "$PROFILE" >/dev/null <<EOF
# Generated by Shiodoki desktop/scripts/setup-linux-sandbox.sh
abi <abi/4.0>,
include <tunables/global>

profile $NAME "$ELECTRON" flags=(unconfined) {
  userns,

  include if exists <local/$NAME>
}
EOF
sudo apparmor_parser -r "$PROFILE"
echo "Done. Run 'npm run dev' again."
